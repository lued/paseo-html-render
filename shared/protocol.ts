import { defineRpc } from "@getpaseo/plugin";
import { z } from "zod";
import {
  MAX_ASSET_BASE64_CHARS,
  MAX_ASSET_PNG_BYTES,
  MAX_CAPTURED_HEIGHT,
  MAX_GRAPH_DECISIONS,
  MAX_GRAPH_EDGES,
  MAX_GRAPH_ID_CHARS,
  MAX_GRAPH_NODES,
  MAX_HTML_CHARS,
  MAX_INTERACTIVE_HTML_BYTES,
  MAX_INTERACTIVE_HTML_CHARS,
  MAX_MARKER_HEIGHTS,
  MAX_PATH_CHARS,
  MAX_PREVIEW_PNG_BYTES,
  MAX_REPORT_BYTES,
  MAX_SUMMARY_CHARS,
  MAX_TITLE_CHARS,
  PREVIEW_MAX_WIDTH,
  PREVIEW_MIN_WIDTH,
} from "./limits.ts";
import { isSafeHttpUrl, reportModelSchema, utf8ByteLength, type ReportModelV1 } from "./report-model.ts";

/** Artifact ids are 32 lowercase hex characters, generated by the daemon. */
export const artifactIdSchema = z
  .string()
  .regex(/^[0-9a-f]{32}$/, "artifact id must be 32 lowercase hex characters");

export const agentIdSchema = z.string().min(1).max(200);

/** Timeline renderer payload. Kept small: it is rebuilt from persisted tool output. */
export const renderModeSchema = z.enum(["static", "auto", "iframe"]).optional();
export type RenderMode = z.output<typeof renderModeSchema>;

/** One measured width/height pair. Widths are strictly ascending within a list. */
export const measuredHeightTupleSchema = z.tuple([
  z.number().int().min(PREVIEW_MIN_WIDTH).max(PREVIEW_MAX_WIDTH),
  z.number().int().min(1).max(MAX_CAPTURED_HEIGHT),
]);
export type MeasuredHeight = z.output<typeof measuredHeightTupleSchema>;

export const measuredHeightsSchema = z
  .array(measuredHeightTupleSchema)
  .max(MAX_MARKER_HEIGHTS)
  .refine(
    (heights) => heights.every((entry, index) => index === 0 || entry[0] > heights[index - 1]![0]),
    "heights must be sorted ascending by width and contain no duplicates",
  );
export type MeasuredHeights = z.output<typeof measuredHeightsSchema>;

/**
 * Timeline renderer payload. Kept small: it is rebuilt from persisted tool
 * output. It holds references and bounded metadata only; the report body and
 * HTML never appear in a marker.
 */
export const reportCardSchema = z.object({
  artifactId: artifactIdSchema,
  title: z.string().min(1).max(MAX_TITLE_CHARS),
  summary: z.string().max(MAX_SUMMARY_CHARS).nullable(),
  width: z.number().int().min(1).max(10_000),
  height: z.number().int().min(1).max(MAX_CAPTURED_HEIGHT),
  /** Experimental web-only inline HTML mode; absent means static PNG. */
  renderMode: renderModeSchema,
  /** True when report.json exists and the native report UI can read it. */
  hasReport: z.boolean().optional(),
  /** Capture height measured at the default width; the requested `height` stays the frame. */
  measuredHeight: z.number().int().min(1).max(MAX_CAPTURED_HEIGHT).optional(),
  /** Optional multi-width measurements, bounded and sorted by width. */
  heights: measuredHeightsSchema.optional(),
});
export type ReportCardData = z.output<typeof reportCardSchema>;

/** Named raster assets a client may request. The report body is never an asset. */
export const reportAssetNameSchema = z.enum(["preview", "previewLight", "graphDark", "graphLight"]);
export type ReportAssetName = z.output<typeof reportAssetNameSchema>;

function base64DecodedBytes(value: string): number {
  const padding = value.endsWith("==") ? 2 : value.endsWith("=") ? 1 : 0;
  return Math.floor((value.length * 3) / 4) - padding;
}

/** Base64 image payload bounded by binary bytes, not only by string length. */
export const boundedBase64ImageSchema = z
  .string()
  .min(4)
  .max(MAX_ASSET_BASE64_CHARS)
  .regex(/^[A-Za-z0-9+/]+={0,2}$/, "base64 payload contains invalid characters")
  .refine((value) => base64DecodedBytes(value) <= MAX_ASSET_PNG_BYTES, "decoded image exceeds the asset budget");

const INTERACTIVE_PATH_CONTROL = /[\u0000-\u001F\u007F]/;

export const reportPreviewSchema = z.object({
  mimeType: z.literal("image/png"),
  base64: boundedBase64ImageSchema,
});

/** Absolute path to interactive.html; Paseo's file preview consumes it as text. */
export const interactivePathSchema = z
  .string()
  .min(1)
  .max(MAX_PATH_CHARS)
  .refine(
    (value) => !INTERACTIVE_PATH_CONTROL.test(value) && (value.startsWith("/") || /^[A-Za-z]:[\\/]/.test(value)),
    "interactivePath must be an absolute path",
  );

/** Bounded CSP-protected interactive.html read. The original HTML bound is unchanged. */
export const interactiveHtmlSchema = z
  .string()
  .min(1)
  .max(MAX_INTERACTIVE_HTML_CHARS)
  .refine(
    (value) => utf8ByteLength(value) <= MAX_INTERACTIVE_HTML_BYTES,
    `interactiveHtml exceeds ${MAX_INTERACTIVE_HTML_BYTES} bytes`,
  );

/** Metadata for server-generated graph previews; node/edge lists live in the report. */
export const graphMetadataSchema = z.object({
  id: z.string().min(1).max(MAX_GRAPH_ID_CHARS).optional(),
  nodeCount: z.number().int().min(0).max(MAX_GRAPH_NODES),
  edgeCount: z.number().int().min(0).max(MAX_GRAPH_EDGES),
  decisionCount: z.number().int().min(0).max(MAX_GRAPH_DECISIONS),
  previewLight: z.boolean().optional(),
  previewDark: z.boolean().optional(),
});
export type GraphMetadata = z.output<typeof graphMetadataSchema>;

export const themePreviewMetadataSchema = z.object({
  light: z.boolean(),
  dark: z.boolean(),
});
export type ThemePreviewMetadata = z.output<typeof themePreviewMetadataSchema>;

export const reportAssetsMetadataSchema = z.object({
  previewLight: z.boolean(),
  graphDark: z.boolean(),
  graphLight: z.boolean(),
});
export type ReportAssetsMetadata = z.output<typeof reportAssetsMetadataSchema>;

/**
 * Existing required fields stay required so the current server and clients keep
 * typechecking while downstream handlers catch up. Every new field is optional.
 */
export const readArtifactRpc = defineRpc({
  name: "html.artifact.read",
  input: z.object({ artifactId: artifactIdSchema, agentId: agentIdSchema }),
  output: z.object({
    artifactId: artifactIdSchema,
    title: z.string().min(1).max(MAX_TITLE_CHARS),
    summary: z.string().max(MAX_SUMMARY_CHARS).nullable(),
    width: z.number().int().min(1),
    height: z.number().int().min(1),
    createdAt: z.string(),
    preview: reportPreviewSchema,
    /** Measured capture height; absent for legacy artifacts. */
    measuredHeight: z.number().int().min(1).max(MAX_CAPTURED_HEIGHT).optional(),
    heights: measuredHeightsSchema.optional(),
    /** True when a bounded report is stored and safe to render natively. */
    hasReport: z.boolean().optional(),
    /** The report itself, or null when this artifact predates reports. */
    report: reportModelSchema.nullable().optional(),
    interactivePath: interactivePathSchema.optional(),
    themePreview: themePreviewMetadataSchema.optional(),
    graph: graphMetadataSchema.optional(),
    assets: reportAssetsMetadataSchema.optional(),
  }),
});

export const readOriginalArtifactRpc = defineRpc({
  name: "html.artifact.original",
  input: z.object({ artifactId: artifactIdSchema, agentId: agentIdSchema }),
  output: z.object({
    artifactId: artifactIdSchema,
    title: z.string().min(1).max(MAX_TITLE_CHARS),
    html: z.string().min(1).max(MAX_HTML_CHARS),
    /** CSP-protected, image-inlined copy for Paseo's HTML file preview. */
    interactiveHtml: interactiveHtmlSchema.optional(),
    interactivePath: interactivePathSchema.optional(),
  }),
});

/** Dedicated bounded report read. Native clients always receive `report: null` when absent. */
export const readReportRpc = defineRpc({
  name: "html.artifact.report",
  input: z.object({ artifactId: artifactIdSchema, agentId: agentIdSchema }),
  output: z.object({
    artifactId: artifactIdSchema,
    report: reportModelSchema.nullable(),
  }),
});

/** One named PNG asset. Base64 output is bounded by `MAX_ASSET_PNG_BYTES`. */
export const readAssetRpc = defineRpc({
  name: "html.artifact.asset",
  input: z.object({
    artifactId: artifactIdSchema,
    agentId: agentIdSchema,
    asset: reportAssetNameSchema,
  }),
  output: z.object({
    artifactId: artifactIdSchema,
    asset: reportAssetNameSchema,
    mimeType: z.literal("image/png"),
    base64: boundedBase64ImageSchema,
    byteLength: z.number().int().min(1).max(MAX_PREVIEW_PNG_BYTES),
    width: z.number().int().min(1).optional(),
    height: z.number().int().min(1).optional(),
  }),
});

/** Internal: shape of a stored artifact manifest. Never sent to a client verbatim. */
export const artifactManifestSchema = z.object({
  version: z.literal(1),
  artifactId: artifactIdSchema,
  title: z.string().min(1).max(MAX_TITLE_CHARS),
  summary: z.string().max(MAX_SUMMARY_CHARS).nullable(),
  width: z.number().int().min(1),
  height: z.number().int().min(1),
  htmlBytes: z.number().int().min(1),
  createdAt: z.string(),
  workspaceId: z.string().min(1),
  ownerCwd: z.string().min(1),
  measuredHeight: z.number().int().min(1).max(MAX_CAPTURED_HEIGHT).optional(),
  heights: measuredHeightsSchema.optional(),
  /** Stored report body. Bounded by MAX_REPORT_BYTES; absent for legacy artifacts. */
  report: reportModelSchema.optional(),
  reportBytes: z.number().int().min(1).max(MAX_REPORT_BYTES).optional(),
  interactiveBytes: z.number().int().min(1).max(MAX_INTERACTIVE_HTML_BYTES).optional(),
  themePreview: themePreviewMetadataSchema.optional(),
  graph: graphMetadataSchema.optional(),
});
export type ArtifactManifest = z.output<typeof artifactManifestSchema>;

/** Re-exported so downstream packages have one import site for the report contract. */
export { reportModelSchema };
export type { ReportModelV1 };

/** Inferred RPC result shapes downstream handlers and clients can name directly. */
export type ReadArtifactResult = z.output<typeof readArtifactRpc.output>;
export type ReadOriginalArtifactResult = z.output<typeof readOriginalArtifactRpc.output>;
export type ReadReportResult = z.output<typeof readReportRpc.output>;
export type ReadAssetInput = z.input<typeof readAssetRpc.input>;
export type ReadAssetResult = z.output<typeof readAssetRpc.output>;

/** Shared URL/path guards for handlers that surface evidence or file links. */
export { isSafeHttpUrl };
